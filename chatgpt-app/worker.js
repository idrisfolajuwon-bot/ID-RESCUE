const API_ORIGIN = "https://idrisfolajuwon-bot.github.io";
const SERVER_NAME = "idris-ai-studio";
const SERVER_VERSION = "0.1.0";
const PROTOCOL_VERSION = "2025-03-26";
const MAX_REQUEST_BYTES = 16000;


function json(data, status = 200, extraHeaders = {}) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "POST, GET, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type, Mcp-Protocol-Version, Mcp-Session-Id, Last-Event-ID",
      "Vary": "Origin",
      ...extraHeaders
    }
  });
}

function rpcResult(id, result) {
  return json({ jsonrpc: "2.0", id, result });
}

function rpcError(id, code, message) {
  return json({ jsonrpc: "2.0", id, error: { code, message } });
}

function toolError(message) {
  return { isError: true, content: [{ type: "text", text: message }] };
}

function toolText(message) {
  return { isError: false, content: [{ type: "text", text: message }] };
}

async function applyRateLimit(request, env, weight) {
  if (!env.IDRIS_MCP_CLIENT_LIMIT || !env.IDRIS_MCP_GLOBAL_LIMIT) return false;
  const ip = request.headers.get("CF-Connecting-IP") || "unknown-client";
  try {
    const [client, global] = await Promise.all([
      env.IDRIS_MCP_CLIENT_LIMIT.limit({ key: ip, delta: weight }),
      env.IDRIS_MCP_GLOBAL_LIMIT.limit({ key: "all-users", delta: weight })
    ]);
    return Boolean(client.success && global.success);
  } catch {
    return false;
  }
}

async function postBackend(path, body) {
  const response = await fetch(API_BASE + path, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Origin": API_ORIGIN
    },
    body: JSON.stringify(body),
    signal: AbortSignal.timeout(60000),
    cache: "no-store"
  });

  if (!response.ok) {
    const detail = (await response.text()).slice(0, 300);
    throw new Error("IDRIS AI STUDIO backend returned HTTP " + response.status + (detail ? ": " + detail : "."));
  }
  return response;
}

async function askIdris(question) {
  const safetyGuidance = "Keep every answer suitable for a general audience. Do not provide explicit sexual content, instructions for self-harm, dangerous acts, weapon use, or graphic violence. For risky requests, respond briefly and safely. Be accurate, clear, and honest about uncertainty.";
  const response = await postBackend("/chat", {
    messages: [
      { role: "system", content: safetyGuidance },
      { role: "user", content: question }
    ]
  });
  const data = await response.json();
  if (!data || typeof data.reply !== "string" || !data.reply.trim()) {
    throw new Error("IDRIS AI STUDIO did not return a readable answer.");
  }

  let output = data.reply.trim();
  const sources = Array.isArray(data.sources) ? data.sources.slice(0, 6) : [];
  if (sources.length) {
    output += "\n\nSources from IDRIS AI STUDIO's live research:";
    for (let i = 0; i < sources.length; i++) {
      const source = sources[i] || {};
      if (typeof source.url === "string" && /^https?:\/\//i.test(source.url)) {
        output += "\n[" + (i + 1) + "] " + String(source.title || "Source").slice(0, 180) + " — " + source.url;
      }
    }
  }
  return toolText(output);
}

function arrayBufferToBase64(buffer) {
  const bytes = new Uint8Array(buffer);
  let binary = "";
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, Math.min(i + chunkSize, bytes.length)));
  }
  return btoa(binary);
}

async function createImage(prompt) {
  const safetyPrompt = prompt + ". Create an age-appropriate image for a general audience. Do not include sexual content, graphic violence, self-harm, or dangerous activity.";
  const response = await postBackend("/image", { prompt: safetyPrompt });
  const mimeType = response.headers.get("Content-Type") || "image/png";
  if (!mimeType.toLowerCase().startsWith("image/")) {
    throw new Error("The image service returned an unsupported response.");
  }
  const buffer = await response.arrayBuffer();
  if (!buffer.byteLength || buffer.byteLength > 6 * 1024 * 1024) {
    throw new Error("The generated image was empty or larger than the supported limit.");
  }

  return {
    isError: false,
    content: [
      { type: "image", data: arrayBufferToBase64(buffer), mimeType },
      { type: "text", text: "Image generated by IDRIS AI STUDIO, an independent I D LABS product." }
    ]
  };
}

async function callTool(request, env, name, args) {
  if (name === "ask_idris_ai") {
    const question = typeof args.question === "string" ? args.question.trim() : "";
    if (!question || question.length > 6000) return toolError("Enter a question of up to 6,000 characters.");
    if (!(await applyRateLimit(request, env, 1))) return toolError("The IDRIS AI STUDIO request limit has been reached. Please wait a minute and try again.");
    try {
      return await askIdris(question);
    } catch (error) {
      return toolError("IDRIS AI STUDIO could not complete the request. " + String(error.message || error).slice(0, 260));
    }
  }

  if (name === "create_image") {
    const prompt = typeof args.prompt === "string" ? args.prompt.trim() : "";
    if (prompt.length < 5 || prompt.length > 1600) return toolError("Describe the image in 5 to 1,600 characters.");
    if (!(await applyRateLimit(request, env, 4))) return toolError("The image request limit has been reached. Please wait a minute and try again.");
    try {
      return await createImage(prompt);
    } catch (error) {
      return toolError("IDRIS AI STUDIO could not create the image. " + String(error.message || error).slice(0, 260));
    }
  }

  return toolError("That IDRIS AI STUDIO tool is not available.");
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === "OPTIONS") {
      return new Response(null, {
        status: 204,
        headers: {
          "Access-Control-Allow-Origin": "*",
          "Access-Control-Allow-Methods": "POST, GET, OPTIONS",
          "Access-Control-Allow-Headers": "Content-Type, Mcp-Protocol-Version, Mcp-Session-Id, Last-Event-ID",
          "Access-Control-Max-Age": "86400"
        }
      });
    }

    if (url.pathname === "/health" && request.method === "GET") {
      return json({
        ok: true,
        name: SERVER_NAME,
        version: SERVER_VERSION,
        endpoint: "/mcp",
        tools: TOOLS.map(tool => tool.name)
      });
    }

    if (url.pathname !== "/mcp") return json({ error: "Not found." }, 404);
    if (request.method !== "POST") {
      return json({ error: "Use POST for the MCP endpoint." }, 405, { Allow: "POST, OPTIONS" });
    }

    const declaredLength = Number(request.headers.get("Content-Length") || 0);
    if (declaredLength > MAX_REQUEST_BYTES) return json({ error: "Request is too large." }, 413);

    let raw;
    try {
      raw = await request.text();
      if (new TextEncoder().encode(raw).byteLength > MAX_REQUEST_BYTES) return json({ error: "Request is too large." }, 413);
    } catch {
      return json({ error: "Could not read request body." }, 400);
    }

    let message;
    try {
      message = JSON.parse(raw);
    } catch {
      return json({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "Parse error." } }, 400);
    }

    if (!message || typeof message !== "object" || Array.isArray(message) || message.jsonrpc !== "2.0" || typeof message.method !== "string") {
      return json({ jsonrpc: "2.0", id: null, error: { code: -32600, message: "Invalid JSON-RPC request." } }, 400);
    }

    const hasId = Object.prototype.hasOwnProperty.call(message, "id");
    const id = hasId ? message.id : null;
    const params = message.params && typeof message.params === "object" ? message.params : {};

    if (message.method.startsWith("notifications/")) {
      return new Response(null, { status: 202, headers: { "Cache-Control": "no-store" } });
    }

    if (message.method === "initialize") {
      const requestedVersion = typeof params.protocolVersion === "string" ? params.protocolVersion : PROTOCOL_VERSION;
      const supported = ["2025-03-26", "2024-11-05"];
      return rpcResult(id, {
        protocolVersion: supported.includes(requestedVersion) ? requestedVersion : PROTOCOL_VERSION,
        capabilities: { tools: { listChanged: false } },
        serverInfo: { name: SERVER_NAME, version: SERVER_VERSION },
        instructions: "IDRIS AI STUDIO is an independent AI workspace developed under I D LABS. Use ask_idris_ai for text questions and create_image for original image generation. Be clear that IDRIS AI STUDIO is not ChatGPT and is not an OpenAI product."
      });
    }

    if (message.method === "ping") return rpcResult(id, {});
    if (message.method === "tools/list") return rpcResult(id, { tools: TOOLS });

    if (message.method === "tools/call") {
      const name = typeof params.name === "string" ? params.name : "";
      const args = params.arguments && typeof params.arguments === "object" ? params.arguments : {};
      const result = await callTool(request, env, name, args);
      return rpcResult(id, result);
    }

    if (message.method === "resources/list") return rpcResult(id, { resources: [] });
    if (message.method === "prompts/list") return rpcResult(id, { prompts: [] });

    return rpcError(id, -32601, "Method not found.");
  }
};
